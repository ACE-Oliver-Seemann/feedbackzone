// Builds TEST_CASES_BACKEND.md from evidence/backend/results.json (written by run-all.mjs).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const REP = path.join(ROOT, "testing", "reports", "2026-11-12_001");
const results = JSON.parse(fs.readFileSync(path.join(REP, "evidence", "backend", "results.json"), "utf8"));
const esc = (s) => String(s ?? "").replace(/\|/g, "\|").replace(/\r?\n/g, " ").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/c[a-z0-9]{24}/g, ":id");
const cut = (s, n) => (s.length > n ? s.slice(0, n) + "…" : s);
const c = { PASS: 0, FAIL: 0, BLOCKED: 0 };
for (const r of results) c[r.status]++;
let out = `# Backend test cases – session 2026-11-12_001 (Agent 1)\n\n`;
out += `Generated by \`testing/scripts/backend/gen-cases.mjs\` from \`evidence/backend/results.json\` (one row per executed test).\n\n`;
out += `**Executed ${results.length} · PASS ${c.PASS} · FAIL ${c.FAIL} · BLOCKED ${c.BLOCKED}**\n\n`;
out += `Environment: \`http://localhost:3301\` (production build), database \`prisma/qa-backend.db\`. Ids of the form \`c…\` are shown as \`:id\`. `;
out += `Accounts: hr = HR, mA/mB = manager Alfa/Beta, a1–a5 = employees Alfa (adam, barbora, cyril, dana, emil), b1–b5 = employees Beta (filip, gabriela, hugo, ivana, jakub).\n`;
out += `Full request/response pairs of every test are in \`evidence/backend/requests.jsonl\` (field \`test\`), console output in \`evidence/backend/run-output.txt\`.\n`;
let suite = "";
for (const r of results) {
  if (r.suite !== suite) {
    suite = r.suite;
    const rs = results.filter((x) => x.suite === suite);
    out += `\n## ${suite}\n\n${rs.length} tests · PASS ${rs.filter((x) => x.status === "PASS").length} · FAIL ${rs.filter((x) => x.status === "FAIL").length} · BLOCKED ${rs.filter((x) => x.status === "BLOCKED").length}\n\n`;
    out += `| Test ID | Area | Description | Preconditions | Steps | Expected | Actual | Status | Evidence |\n|---|---|---|---|---|---|---|---|---|\n`;
  }
  out += `| ${r.id} | ${r.area} | ${esc(r.desc)} | ${esc(cut(r.pre, 160))} | ${esc(cut(r.steps, 330))} | ${esc(cut(r.expected, 260))} | ${esc(cut(r.actual, 260))} | **${r.status}** | results.json#${r.id} |\n`;
}
fs.writeFileSync(path.join(REP, "TEST_CASES_BACKEND.md"), out);
console.log(`written ${results.length} rows`);
