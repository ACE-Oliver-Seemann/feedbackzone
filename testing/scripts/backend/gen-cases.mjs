// Builds TEST_CASES_BACKEND.md from the result files in evidence/backend/ of one session:
//   results.json      – regression baseline, written by run-all.mjs        (ids BE-T…)
//   results-new.json  – new suite of the session, written by run-session2.mjs (ids BE2-T…), if present
// Usage: node testing/scripts/backend/gen-cases.mjs            (session from QA_SESSION, default 2026-11-12_002)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const SESSION = process.env.QA_SESSION || "2026-11-12_002";
const REP = path.join(ROOT, "testing", "reports", SESSION);
const load = (name) => {
  const file = path.join(REP, "evidence", "backend", name);
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")).map((r) => ({ ...r, file: name })) : [];
};
const parts = [
  ["Part A – regression baseline (suites S1–S9 of session 001, re-executed)", load("results.json"), "requests.jsonl", "run-output-baseline.txt"],
  ["Part B – new tests of this session (suites N1–N13)", load("results-new.json"), "requests-new.jsonl", "run-output-new.txt"],
].filter((p) => p[1].length > 0);
const results = parts.flatMap((p) => p[1]);
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/c[a-z0-9]{24}/g, ":id");
const cut = (s, n) => (s.length > n ? s.slice(0, n) + "…" : s);
const count = (rs) => { const c = { PASS: 0, FAIL: 0, BLOCKED: 0 }; for (const r of rs) c[r.status]++; return c; };
const c = count(results);
let out = `# Backend test cases – session ${SESSION} (Agent 1)\n\n`;
out += `Generated by \`testing/scripts/backend/gen-cases.mjs\` from the result files in \`evidence/backend/\` (one row per executed test).\n\n`;
out += `**Executed ${results.length} · PASS ${c.PASS} · FAIL ${c.FAIL} · BLOCKED ${c.BLOCKED}**\n\n`;
for (const [title, rs] of parts) { const x = count(rs); out += `- ${title}: ${rs.length} executed · PASS ${x.PASS} · FAIL ${x.FAIL} · BLOCKED ${x.BLOCKED}\n`; }
out += `\nEnvironment: \`http://localhost:3301\` (production build), database \`prisma/qa-backend.db\`. Ids of the form \`c…\` are shown as \`:id\`. `;
out += `Accounts: hr = HR, mA/mB = manager Alfa/Beta, a1–a5 = employees Alfa (adam, barbora, cyril, dana, emil), b1–b5 = employees Beta (filip, gabriela, hugo, ivana, jakub). All accounts are invented seed data.\n`;
out += `Full request/response pairs of every test are in the \`requests*.jsonl\` file named in each part (field \`test\`); the console output is in the \`run-output-*.txt\` file.\n`;
for (const [title, rs, reqFile, runFile] of parts) {
  out += `\n# ${title}\n\nEvidence: \`evidence/backend/${rs[0].file}\`, \`evidence/backend/${reqFile}\`, \`evidence/backend/${runFile}\`.\n`;
  let suite = "";
  for (const r of rs) {
    if (r.suite !== suite) {
      suite = r.suite;
      const x = count(rs.filter((y) => y.suite === suite));
      out += `\n## ${suite}\n\n${x.PASS + x.FAIL + x.BLOCKED} tests · PASS ${x.PASS} · FAIL ${x.FAIL} · BLOCKED ${x.BLOCKED}\n\n`;
      out += `| Test ID | Area | Description | Preconditions | Steps | Expected | Actual | Status | Evidence |\n|---|---|---|---|---|---|---|---|---|\n`;
    }
    out += `| ${r.id} | ${r.area} | ${esc(r.desc)} | ${esc(cut(r.pre, 160))} | ${esc(cut(r.steps, 330))} | ${esc(cut(r.expected, 260))} | ${esc(cut(r.actual, 260))} | **${r.status}** | ${r.file}#${r.id} |\n`;
  }
}
fs.writeFileSync(path.join(REP, "TEST_CASES_BACKEND.md"), out);
console.log(`written ${results.length} rows (${JSON.stringify(c)})`);
